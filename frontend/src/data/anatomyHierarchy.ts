export type GenderFilter = 'all' | 'male' | 'female';
export type AssetStatus = 'READY' | 'PARTIAL' | 'PLACEHOLDER' | 'MISSING';

export interface AnatomicalRelationship {
  type: 'contains' | 'part_of' | 'supplies' | 'innervates' | 'connected_to' | 'adjacent_to';
  targetId: string;
  targetNameVi: string;
  targetNameEn: string;
}

export interface AnatomicalStructure {
  id: string; // Unique ID (e.g. "heart", "left_ventricle", "skull")
  systemId: string; // Belongs to system (e.g. "cardiovascular", "skeletal")
  parentId?: string; // Hierarchical parent structure ID
  childrenIds: string[];
  layerIndex: number; // 1 (Skin) to 8 (Deep)
  category: 'organ' | 'bone' | 'muscle' | 'vessel' | 'nerve' | 'gland' | 'tissue' | 'joint';
  gender: GenderFilter; // 'all' | 'male' | 'female'
  modelFile?: string; // Path to real GLB model in /models/

  // Trilingual Naming & Synonyms
  nameVi: string;
  nameEn: string;
  nameLatin?: string;
  synonyms: string[];

  // Spatial & Transform Data
  position: [number, number, number]; // [x, y, z] in standard 1.8m standing human coordinate frame
  boundingBox?: {
    min: [number, number, number];
    max: [number, number, number];
  };

  // Clinical & Anatomical Dossier
  descriptionVi: string;
  descriptionEn: string;
  locationVi?: string;
  locationEn?: string;
  functionVi?: string;
  functionEn?: string;
  bloodSupplyVi?: string;
  bloodSupplyEn?: string;
  innervationVi?: string;
  innervationEn?: string;
  clinicalNotesVi?: string;
  clinicalNotesEn?: string;
  icd10?: string[];

  relationships: AnatomicalRelationship[];
  reviewStatus: 'draft' | 'reviewed' | 'verified';
  assetStatus: AssetStatus;
  referenceSource: string;
}

