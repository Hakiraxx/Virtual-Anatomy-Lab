export function searchAnatomyStructures(query: string, gender: GenderFilter = 'all'): AnatomicalStructure[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const baseResults = Object.values(ANATOMICAL_STRUCTURES).filter((st) => {
    if (st.gender !== 'all' && gender !== 'all' && st.gender !== gender) {
      return false;
    }
    if (st.nameVi.toLowerCase().includes(q)) return true;
    if (st.nameEn.toLowerCase().includes(q)) return true;
    if (st.nameLatin && st.nameLatin.toLowerCase().includes(q)) return true;
    if (st.synonyms.some((syn) => syn.toLowerCase().includes(q))) return true;
    if (st.clinicalNotesVi && st.clinicalNotesVi.toLowerCase().includes(q)) return true;
    return false;
  });

  // Include Craniofacial Lab structures (Cranial Nerves, Foramina, FDI Teeth, Muscles)
  const craniofacialResults: AnatomicalStructure[] = [];

  // 1. Nerves
  Object.values(DENTAL_NERVE_STRUCTURES).forEach((nerve) => {
    if (
      nerve.nameVi.toLowerCase().includes(q) ||
      nerve.nameEn.toLowerCase().includes(q) ||
      nerve.latinName.toLowerCase().includes(q) ||
      (nerve.division && nerve.division.toLowerCase().includes(q)) ||
      (nerve.cranialNerveNumber && `cn ${nerve.cranialNerveNumber}`.includes(q)) ||
      (nerve.id.includes('ian') && q.includes('ian'))
    ) {
      craniofacialResults.push({
        id: nerve.id,
        systemId: 'craniofacial',
        childrenIds: [],
        layerIndex: 7,
        category: 'nerve',
        gender: 'all',
        nameVi: nerve.nameVi,
        nameEn: nerve.nameEn,
        nameLatin: nerve.latinName,
        synonyms: [nerve.division || '', `CN ${nerve.cranialNerveNumber || ''}`, nerve.id].filter(Boolean),
        position: nerve.path3D && nerve.path3D.length > 0 ? nerve.path3D[0] : [0, 1.34, 0.12],
        descriptionVi: nerve.courseVi,
        descriptionEn: nerve.courseEn,
        clinicalNotesVi: nerve.clinicalAnatomyVi,
        clinicalNotesEn: nerve.clinicalAnatomyEn,
        relationships: [],
        reviewStatus: 'verified',
        assetStatus: 'READY',
        referenceSource: nerve.references ? `TA: ${nerve.references.terminologiaAnatomica}` : 'Netter'
      });
    }
  });

  // 2. Foramina
  Object.values(CRANIAL_FORAMINA).forEach((f) => {
    if (
      f.nameVi.toLowerCase().includes(q) ||
      f.nameEn.toLowerCase().includes(q) ||
      f.latinName.toLowerCase().includes(q) ||
      f.boneVi.toLowerCase().includes(q)
    ) {
      craniofacialResults.push({
        id: f.id,
        systemId: 'craniofacial',
        childrenIds: [],
        layerIndex: 4,
        category: 'bone',
        gender: 'all',
        nameVi: f.nameVi,
        nameEn: f.nameEn,
        nameLatin: f.latinName,
        synonyms: [f.boneVi, f.boneEn, f.id],
        position: f.position,
        descriptionVi: `Lỗ giải phẫu xương sọ trên ${f.boneVi}. Cấu trúc đi qua: ${f.structuresPassingThroughVi.join(', ')}.`,
        descriptionEn: `Cranial foramen in ${f.boneEn}. Transmitted structures: ${f.structuresPassingThroughEn.join(', ')}.`,
        clinicalNotesVi: f.clinicalSignificanceVi,
        clinicalNotesEn: f.clinicalSignificanceEn,
        relationships: [],
        reviewStatus: 'verified',
        assetStatus: 'READY',
        referenceSource: 'Gray\'s Anatomy'
      });
    }
  });

  // 3. 32 Authoritative FDI Teeth (from ToothRegistry)
  Object.values(TOOTH_REGISTRY).forEach((t) => {
    const fdiStr = `${t.fdi}`;
    const cleanQ = q.replace(/[\s._-]/g, '');
    const isMatch =
      t.nameVi.toLowerCase().includes(q) ||
      t.nameEn.toLowerCase().includes(q) ||
      t.latinName.toLowerCase().includes(q) ||
      `răng ${t.fdi}`.includes(q) ||
      `rang ${t.fdi}`.includes(q) ||
      `r${t.fdi}` === cleanQ ||
      `tooth${t.fdi}` === cleanQ ||
      `fdi${t.fdi}` === cleanQ ||
      fdiStr === q ||
      `#${t.universalNumber}` === q ||
      t.meshNodeName.toLowerCase().includes(q);

    if (isMatch) {
      craniofacialResults.push({
        id: t.legacyId, // "tooth_46"
        systemId: 'craniofacial',
        childrenIds: [],
        layerIndex: 4,
        category: 'bone',
        gender: 'all',
        nameVi: t.nameVi,
        nameEn: t.nameEn,
        nameLatin: t.latinName,
        synonyms: [
          `răng ${t.fdi}`,
          `r.${t.fdi}`,
          `r${t.fdi}`,
          `FDI ${t.fdi}`,
          `#${t.universalNumber}`,
          t.palmer,
          t.meshNodeName,
          t.id
        ],
        position: t.craniofacialPos,
        descriptionVi: `${t.nameVi} (FDI ${t.fdi}, Universal #${t.universalNumber}, Palmer ${t.palmer}). Thuộc cung ${t.jaw === 'MAXILLA' ? 'hàm trên' : 'hàm dưới'} bên ${t.side === 'RIGHT' ? 'phải' : 'trái'} (Cung ${t.quadrant}). Có ${t.morphology.rootCount} chân răng và ${t.morphology.canalCount} ống tủy (${t.morphology.canalNames.join(', ')}). Răng đối vận: ${t.opposingTooth || 'None'}. Răng kế cận: Gần (${t.mesialAdjacent || 'Đường giữa'}), Xa (${t.distalAdjacent || 'Không'}).`,
        descriptionEn: `${t.nameEn} (FDI ${t.fdi}, Universal #${t.universalNumber}). ${t.jaw} ${t.side.toLowerCase()}, Quadrant ${t.quadrant}. ${t.morphology.rootCount} roots, ${t.morphology.canalCount} canals (${t.morphology.canalNames.join(', ')}). Vertucci Class: ${t.morphology.vertucciClass}.`,
        clinicalNotesVi: `Gây tê khuyến nghị: ${t.morphology.recommendedAnesthesiaVi.join(', ')}. Nguy cơ lâm sàng: ${t.morphology.clinicalRisksVi.join('; ')}.`,
        clinicalNotesEn: `Innervation: ${t.pulpInnervationId} (pulp), ${t.buccalGingivaInnervationId} (buccal). Mesh: ${t.meshNodeName}.`,
        relationships: [
          ...(t.mesialAdjacent ? [{ type: 'adjacent_to' as const, targetId: t.mesialAdjacent, targetNameVi: `Răng kế cận phía gần`, targetNameEn: `Mesial Adjacent` }] : []),
          ...(t.distalAdjacent ? [{ type: 'adjacent_to' as const, targetId: t.distalAdjacent, targetNameVi: `Răng kế cận phía xa`, targetNameEn: `Distal Adjacent` }] : []),
          ...(t.opposingTooth ? [{ type: 'articulates_with' as const, targetId: t.opposingTooth, targetNameVi: `Răng đối diện khớp cắn`, targetNameEn: `Opposing Occlusal Tooth` }] : [])
        ],
        reviewStatus: 'verified',
        assetStatus: 'READY',
        referenceSource: 'FDI World Dental Federation / Wheeler\'s Dental Anatomy'
      });
    }
  });

  // 4. Muscles of Mastication
  MUSCLES_OF_MASTICATION.forEach((m) => {
    if (
      m.nameVi.toLowerCase().includes(q) ||
      m.nameEn.toLowerCase().includes(q) ||
      m.latinName.toLowerCase().includes(q)
    ) {
      craniofacialResults.push({
        id: m.id,
        systemId: 'craniofacial',
        childrenIds: [],
        layerIndex: 5,
        category: 'muscle',
        gender: 'all',
        nameVi: m.nameVi,
        nameEn: m.nameEn,
        nameLatin: m.latinName,
        synonyms: ['cơ nhai', 'mastication', m.id],
        position: [0.056, 1.745, 0.040],
        descriptionVi: `${m.nameVi}: Nguyên ủy tại ${m.originVi}, bám tận tại ${m.insertionVi}. Động tác: ${m.actionVi}.`,
        descriptionEn: `${m.nameEn}: Origin ${m.originEn}, insertion ${m.insertionEn}. Action: ${m.actionEn}.`,
        relationships: [],
        reviewStatus: 'verified',
        assetStatus: 'READY',
        referenceSource: 'Gray\'s Anatomy'
      });
    }
  });

  return [...baseResults, ...craniofacialResults];
}

